#!/usr/bin/env python3
"""Writes src/data/airports-major.ts: every large airport with scheduled flights, and every other airport
with scheduled flights and an IATA code, from www/airports-world.json (OurAirports, public domain)."""
import json, re, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(root, 'www', 'airports-world.json'), encoding='utf-8'))
C = d.get('countries', {})
def clean(n):
    n = re.sub(r'\s+(International\s+)?(Airport|Aerodrome|Airfield|Air Base|Airstrip)$', '', n.strip())
    n = re.sub(r'\s+International$', '', n)
    return n.strip() or n
rows = []
for a in d['airports']:
    ident, name, city, cc, lat, lon, elev, size, iata, sched = a[:10]
    if not sched or not re.match(r'^[A-Z0-9]{4}$', ident): continue
    if not (size == 2 or (size in (0, 1) and iata)): continue
    rows.append([ident, clean(name), city or clean(name), C.get(cc, cc), round(lon, 4), round(lat, 4)])
rows.sort(key=lambda r: r[0])
out = ['// Generated by scripts/make-major-airports.py from OurAirports (public domain): the well-known airports',
       '// (large ones with scheduled flights, and every other one with scheduled flights and an IATA code).',
       '// They are available from the start, before the full world list has loaded. Hand-checked entries in',
       '// airports.ts take precedence.',
       'const MAJOR_AIRPORTS: [string, string, string, string, number, number][] = [']
out += ['  ' + json.dumps(r, ensure_ascii=False) + ',' for r in rows]
out += ['];', 'for (const r of MAJOR_AIRPORTS) if (!AIRPORTS[r[0]]) AIRPORTS[r[0]] = { icao: r[0], name: r[1], city: r[2], country: r[3], pos: [r[4], r[5]] };', '']
open(os.path.join(root, 'src', 'data', 'airports-major.ts'), 'w', encoding='utf-8').write('\n'.join(out))
print(len(rows), 'airports')
